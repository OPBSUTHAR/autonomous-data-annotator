import { nanoid } from "nanoid";
import type { AnnotatorContext, AnnotatorResult, Annotation } from "./types";

function dimensions(buf: Buffer): { width: number; height: number } | null {
  // PNG
  if (buf.length > 24 && buf[0] === 0x89 && buf[1] === 0x50) {
    return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
  }
  // JPEG
  if (buf[0] === 0xff && buf[1] === 0xd8) {
    let i = 2;
    while (i < buf.length - 9) {
      if (buf[i] !== 0xff) { i++; continue; }
      const marker = buf[i + 1];
      if (marker === 0xc0 || marker === 0xc1 || marker === 0xc2) {
        const h = buf.readUInt16BE(i + 5);
        const w = buf.readUInt16BE(i + 7);
        return { width: w, height: h };
      }
      const len = buf.readUInt16BE(i + 2);
      i += 2 + len;
    }
  }
  // GIF
  if (buf[0] === 0x47 && buf[1] === 0x49 && buf[2] === 0x46) {
    return { width: buf.readUInt16LE(6), height: buf.readUInt16LE(8) };
  }
  return null;
}

function inferLabels(name: string): string[] {
  const base = name.replace(/\.[^.]+$/, "").replace(/[_-]/g, " ");
  const words = base.split(/\s+/).filter(Boolean);
  const labels = words.filter((w) => w.length > 2).slice(0, 5);
  if (labels.length === 0) labels.push("object");
  return Array.from(new Set(labels));
}

export async function annotateImage(ctx: AnnotatorContext): Promise<AnnotatorResult> {
  ctx.onProgress?.("detecting image metadata", 10);
  const dims = dimensions(ctx.buffer);
  ctx.onProgress?.("inferring labels", 40);
  const labels = inferLabels(ctx.file.name);
  const annotations: Annotation[] = [];
  annotations.push({
    id: nanoid(),
    kind: "label",
    data: { label: labels[0], tags: labels, source: "filename-heuristic" },
    confidence: 0.55,
    source: "auto",
  });
  if (dims) {
    annotations.push({
      id: nanoid(),
      kind: "metadata",
      data: { width: dims.width, height: dims.height, aspectRatio: +(dims.width / dims.height).toFixed(3) },
      confidence: 1,
      source: "auto",
    });
    // autogenerated full-canvas box (weak baseline annotator)
    annotations.push({
      id: nanoid(),
      kind: "bbox",
      data: { x: 0.05, y: 0.05, w: 0.9, h: 0.9, label: labels[0], normalized: true },
      confidence: 0.35,
      source: "auto",
    });
  }
  ctx.onProgress?.("done", 100);
  return { fileKind: "image", annotations, metadata: { dimensions: dims, labels } };
}
